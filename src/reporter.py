def generate_report(
        analysis_result: Dict[str, Any],
        errors: List[Dict[str, Any]],
        warnings: List[Dict[str, Any]],
        source_filename: Path
)-> str:
    """Generate the complete plain-text sales report.

    Creates the report header and includes the original source filename and
    generation date.

    The function coordinates the independent report helpers and combines their
    output into a complete plain-text document.

    The report includes:

    - General sales metrics.
    - Overall best-selling product records.
    - Highest-income product records.
    - Highest-income category records.
    - Top 5 best-selling products.
    - Top 5 highest-income products.
    - Product summary.
    - Category summary.
    - Detailed monthly summary with growth metrics.
    - Monthly best-selling products.
    - Monthly highest-income categories.
    - Validation errors.
    - Validation warnings.

    When city analysis is available, the report also includes the
    highest-income city and complete city summary.

    When payment-method analysis is available, the report also includes the
    highest-income payment method and complete payment-method summary.

    Args:
        analysis_result: Dictionary containing metrics, summaries, rankings,
            growth indicators, and highest-performing records produced by the
            sales-analysis process.
        errors: List of dictionaries containing detailed validation errors.
        warnings: List of dictionaries containing non-critical validation
            warnings.
        source_filename: Path representing the original source CSV file.

    Returns:
        A complete plain-text sales report ready to be displayed or saved.
    """
    summary = []
    summary.append("REPORTE DE VENTAS")
    summary.append(f"""
Archivo de origen: {source_filename.name}
Generado el: {date.today()}""")
    summary.append(get_general_summary(analysis_result))
    summary.append(get_best_selling_product(analysis_result))
    summary.append(get_highest_income(analysis_result["highest_income_product"], "PRODUCTO CON MAYOR INGRESO ", "producto_id", "producto"))
    summary.append(get_highest_income(analysis_result["highest_income_category"], "CATEGORÍA CON MAYOR INGRESO", "categoria"))
    if "highest_income_city" in analysis_result.keys():
        summary.append(get_highest_income(analysis_result["highest_income_city"], "CIUDAD CON MAYOR INGRESO", "ciudad"))
    if "highest_income_payment_method" in analysis_result.keys():
        summary.append(get_highest_income(analysis_result["highest_income_payment_method"], "MÉTODO DE PAGO CON MAYOR INGRESO", "metodo_pago"))
    summary.append(get_top_5(analysis_result["top_5_best_selling_products"], "TOP 5 PRODUCTOS MÁS VENDIDOS"))
    summary.append(get_top_5(analysis_result["top_5_highest_income_products"], "TOP 5 PRODUCTOS CON MAYOR INGRESO"))
    summary.append(get_summary(analysis_result["product_summary"], "RESUMEN POR PRODUCTO"))
    summary.append(get_summary(analysis_result["category_summary"], "RESUMEN POR CATEGORÍA"))
    if "city_summary" in analysis_result.keys():
        summary.append(get_summary(analysis_result["city_summary"], "RESUMEN POR CIUDAD"))
    if "payment_method_summary" in analysis_result.keys():
        summary.append(get_summary(analysis_result["payment_method_summary"], "RESUMEN POR MÉTODO DE PAGO"))
    summary.append(get_monthly_summary(analysis_result["monthly_summary"]))
    summary.append(get_monthly_best_selling_product(analysis_result["monthly_best_selling_product"]))
    summary.append(get_monthly_highest_income_category(analysis_result["monthly_highest_income_category"]))
    summary.append(get_errors(errors))
    summary.append(get_warnings(warnings))
    return "\n".join(summary)
